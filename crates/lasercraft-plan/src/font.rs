/// Width of `text` drawn `height` mm tall, mm.
#[must_use]
pub fn width(text: &str, height: f64) -> f64 {
    let n = text.chars().count();
    if n == 0 {
        0.0
    } else {
        (n as f64 * ADVANCE - (ADVANCE - CELL)) * height / HEIGHT
    }
}

/// The strokes of `text` (upper-cased) drawn `height` mm tall, its top left
/// corner at the origin, x right and y down; `place` maps each point to
/// where it goes (to move or turn the text).
#[must_use]
pub fn strokes(text: &str, height: f64, place: impl Fn(Point) -> Point) -> Vec<Vec<Point>> {
    let unit = height / HEIGHT;
    let mut out = Vec::new();
    for (i, c) in text.to_uppercase().chars().enumerate() {
        let x0 = i as f64 * ADVANCE;
        for stroke in glyph(c).unwrap_or_default() {
            out.push(
                stroke
                    .iter()
                    .map(|&(x, y)| place(Point::new((x0 + x) * unit, y * unit)))
                    .collect(),
            );
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_listed_character_has_strokes_inside_its_cell() {
        let chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,-+%()/:×=";
        for c in chars.chars() {
            let g = glyph(c).unwrap_or_else(|| panic!("{c}"));
            for stroke in g {
                assert!(stroke.len() >= 2, "{c}");
                for &(x, y) in *stroke {
                    assert!((0.0..=CELL).contains(&x) && (0.0..=7.0).contains(&y), "{c}");
                }
            }
        }
        assert!(glyph('?').is_none());
    }

    #[test]
    fn text_is_upper_cased_measured_and_placed() {
        assert!((width("ab", 6.0) - 9.0).abs() < 1e-12);
        assert_eq!(width("", 3.0), 0.0);
        let lower = strokes("mm", 6.0, |p| p);
        assert_eq!(lower, strokes("MM", 6.0, |p| p));
        let moved = strokes("1", 6.0, |p| Point::new(p.x + 10.0, p.y));
        assert_eq!(moved[0][0], Point::new(11.0, 1.0));
        assert!(strokes(" ", 6.0, |p| p).is_empty());
    }
}
