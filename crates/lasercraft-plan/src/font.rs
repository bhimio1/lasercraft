//! LaserCraft's single-stroke label font (`docs/spec/test-patterns.md`):
//! own design, uppercase letters, digits and a few symbols as open
//! polylines on a 4 × 6 cell (x right, y down from the top), one unit
//! between characters.

use lasercraft_geom::Point;

/// Cell width, units.
const CELL: f64 = 4.0;
/// Advance per character, units.
const ADVANCE: f64 = 5.0;
/// Cell height, units.
const HEIGHT: f64 = 6.0;

type Glyph = &'static [&'static [(f64, f64)]];

const RING: &[(f64, f64)] = &[
    (1.0, 0.0),
    (3.0, 0.0),
    (4.0, 1.0),
    (4.0, 5.0),
    (3.0, 6.0),
    (1.0, 6.0),
    (0.0, 5.0),
    (0.0, 1.0),
    (1.0, 0.0),
];
const BOWL: &[(f64, f64)] = &[
    (0.0, 6.0),
    (0.0, 0.0),
    (3.0, 0.0),
    (4.0, 1.0),
    (4.0, 2.0),
    (3.0, 3.0),
    (0.0, 3.0),
];

